#!/usr/bin/env python3
"""
Scan the current directory recursively for all .html files (excluding index.html)
and output a window.HTML_CATALOG array in tree.js for automatic loading.

Usage:
  python3 scan.py          # Run once
  python3 scan.py --watch  # Run continuously and update on file changes
"""

import os
import sys
import time
import json

EXCLUDE_DIRS = {'.git', '.gemini', '.vscode', 'node_modules', 'venv', '__pycache__', '.idea'}

def get_html_files(root_dir="."):
    html_files = []
    for dirpath, dirnames, filenames in os.walk(root_dir):
        # Exclude ignored directories in-place
        dirnames[:] = [d for d in dirnames if not d.startswith('.') and d not in EXCLUDE_DIRS]
        
        for file in filenames:
            rel_dir = os.path.relpath(dirpath, root_dir)
            # Skip root index.html
            if rel_dir == "." and file.lower() == "index.html":
                continue
            if file.lower().endswith((".html", ".htm")):
                rel_path = os.path.normpath(os.path.join(rel_dir, file)).replace("\\", "/")
                if rel_path.startswith("./"):
                    rel_path = rel_path[2:]
                html_files.append(rel_path)
    
    html_files.sort(key=lambda s: s.lower())
    return html_files

def generate_catalog(root_dir="."):
    files = get_html_files(root_dir)
    js_content = (
        "// Auto-generated by scan.py - Do not edit manually\n"
        "// Run 'python3 scan.py' or 'python3 scan.py --watch' to refresh\n"
        f"window.HTML_CATALOG = {json.dumps(files, indent=2)};\n"
    )
    output_path = os.path.join(root_dir, "tree.js")
    
    # Check if content changed
    current_content = None
    if os.path.exists(output_path):
        try:
            with open(output_path, "r", encoding="utf-8") as f:
                current_content = f.read()
        except Exception:
            pass
            
    if current_content != js_content:
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(js_content)
        return True, len(files)
    return False, len(files)

def get_snapshot(root_dir="."):
    snapshot = {}
    for dirpath, dirnames, filenames in os.walk(root_dir):
        dirnames[:] = [d for d in dirnames if not d.startswith('.') and d not in EXCLUDE_DIRS]
        for f in filenames:
            if f.lower().endswith((".html", ".htm")):
                p = os.path.join(dirpath, f)
                try:
                    snapshot[p] = os.path.getmtime(p)
                except OSError:
                    pass
    return snapshot

def main():
    watch_mode = "--watch" in sys.argv or "-w" in sys.argv
    root_dir = os.path.dirname(os.path.abspath(__file__))

    changed, count = generate_catalog(root_dir)
    print(f"✓ tree.js updated with {count} HTML file(s).")

    if watch_mode:
        print("👀 Watching for HTML file changes... (Press Ctrl+C to stop)")
        last_snapshot = get_snapshot(root_dir)
        try:
            while True:
                time.sleep(1.2)
                current_snapshot = get_snapshot(root_dir)
                if current_snapshot != last_snapshot:
                    last_snapshot = current_snapshot
                    changed, count = generate_catalog(root_dir)
                    timestamp = time.strftime("%H:%M:%S")
                    print(f"[{timestamp}] 🔄 Detected changes! tree.js updated with {count} HTML file(s).")
        except KeyboardInterrupt:
            print("\nStopped watcher.")

if __name__ == "__main__":
    main()
