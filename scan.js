#!/usr/bin/env node
/**
 * Scan the current directory recursively for all .html files (excluding index.html)
 * and output a window.HTML_CATALOG array in tree.js for automatic loading.
 *
 * Usage:
 *   node scan.js          # Run once
 *   node scan.js --watch  # Run continuously and update on file changes
 */

const fs = require('fs');
const path = require('path');

const EXCLUDE_DIRS = new Set(['.git', '.gemini', '.vscode', 'node_modules', 'venv', '__pycache__', '.idea']);

function getHtmlFiles(dir, rootDir = dir) {
  let results = [];
  const list = fs.readdirSync(dir, { withFileTypes: true });

  for (const dirent of list) {
    if (dirent.name.startsWith('.') || EXCLUDE_DIRS.has(dirent.name)) continue;
    const fullPath = path.join(dir, dirent.name);

    if (dirent.isDirectory()) {
      results = results.concat(getHtmlFiles(fullPath, rootDir));
    } else if (dirent.isFile()) {
      const lower = dirent.name.toLowerCase();
      const relPath = path.relative(rootDir, fullPath).replace(/\\/g, '/');
      if (relPath === 'index.html') continue;
      if (lower.endsWith('.html') || lower.endsWith('.htm')) {
        results.push(relPath);
      }
    }
  }
  return results;
}

function generateCatalog(rootDir = __dirname) {
  const files = getHtmlFiles(rootDir).sort((a, b) => a.localeCompare(b, undefined, { sensitivity: 'base' }));
  const content = `// Auto-generated by scan.js - Do not edit manually\n// Run 'node scan.js' or 'node scan.js --watch' to refresh\nwindow.HTML_CATALOG = ${JSON.stringify(files, null, 2)};\n`;
  const outputPath = path.join(rootDir, 'tree.js');

  let currentContent = null;
  if (fs.existsSync(outputPath)) {
    try { currentContent = fs.readFileSync(outputPath, 'utf8'); } catch (_) {}
  }

  if (currentContent !== content) {
    fs.writeFileSync(outputPath, content, 'utf8');
    return { changed: true, count: files.length };
  }
  return { changed: false, count: files.length };
}

const args = process.argv.slice(2);
const watchMode = args.includes('--watch') || args.includes('-w');
const rootDir = __dirname;

const res = generateCatalog(rootDir);
console.log(`✓ tree.js updated with ${res.count} HTML file(s).`);

if (watchMode) {
  console.log('👀 Watching for HTML file changes... (Press Ctrl+C to stop)');
  fs.watch(rootDir, { recursive: true }, (eventType, filename) => {
    if (!filename) return;
    const lower = filename.toLowerCase();
    if ((lower.endsWith('.html') || lower.endsWith('.htm')) && !lower.includes('index.html')) {
      const update = generateCatalog(rootDir);
      const time = new Date().toLocaleTimeString();
      console.log(`[${time}] 🔄 Detected changes! tree.js updated with ${update.count} HTML file(s).`);
    }
  });
}
